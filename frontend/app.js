function copyReadme() {
  if (window.currentReadme) {
    navigator.clipboard.writeText(window.currentReadme).then(() => {
      alert('✅ README copied to clipboard!');
    }).catch(() => {
      alert('❌ Failed to copy. Please select and copy manually.');
    });
  }
}

